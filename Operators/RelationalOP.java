package Operators;

public class RelationalOP {
    public static void main(String[] args) {
        // relational  -> ==, !=, >= , <= , >,<

        int a = 5;
        int b = 6;

        System.out.println(a == b);
        System.out.println(a != b);
        System.out.println(a >= b);
        System.out.println(a <= b);
        System.out.println(a > b);
        System.out.println(a < b);
    }
}
