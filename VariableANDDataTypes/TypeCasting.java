package VariableANDDataTypes;
// Type casting / explicit type casting
public class TypeCasting {
    public static void main(String[] args) {
        float a =  12.5f;
        int b = (int)a;
        System.out.println(b); // 12

        char ch = 'a';
        int n = ch;
        System.out.println(n); // 97 ascii value
    }
}