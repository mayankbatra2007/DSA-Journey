package VariableANDDataTypes;

public class Variables {
    public static void main(String[] args) {
        int a = 10; // var -> a
        System.out.println(a); // 10

        a = 50;

        System.out.println(a); // 50

        int b = a;

        System.out.println(b);
    }
}
// var -> store data, can change data
